// Writes shared/api-client/platform-routes.js from the Platform Console's route table (src/contracts/api/platform.js):
// the method, path and roles of every route, as plain data, so the console's page can build its client from the table
// without pulling the server's schemas (and zod) into the browser. Run it after changing a platform route:
//
//   npm run gen:platform-routes
//
// test/p7/contract keeps the file and the table in step: a route changed without running this fails there.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { platformRouteList } from '../src/contracts/api/platform.js';

const target = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../shared/api-client/platform-routes.js');

export function platformRoutesSource(list = platformRouteList) {
  const rows = list.map((route) => {
    const fields = [`method: '${route.method}'`, `path: '${route.path}'`, `platformRoles: [${route.platformRoles.map((role) => `'${role}'`).join(', ')}]`];
    if (route.public) fields.push('public: true');
    return `  '${route.id}': { ${fields.join(', ')} },`;
  });
  return `// Generated by scripts/gen-platform-routes.mjs from src/contracts/api/platform.js. Do not edit: run npm run gen:platform-routes.
export const PLATFORM_ROUTES = Object.freeze({
${rows.join('\n')}
});
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(target, platformRoutesSource());
  process.stdout.write(`Wrote ${platformRouteList.length} routes to shared/api-client/platform-routes.js\n`);
}
